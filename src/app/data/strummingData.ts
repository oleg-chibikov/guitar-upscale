import {
  TICKS_IN_BAR,
  TICKS_IN_BEAT,
  TICKS_IN_HALF_BAR,
  TICKS_IN_HALF_BEAT,
  TICKS_IN_SIXTEENTH,
  TICKS_IN_SIXTY_FOURTH,
  TICKS_IN_THIRTY_SECOND,
} from "@/app/engine/clock/clockConstants";

// TODO: Partially merge with clock constants. Move both to data
export const STRUMMING_PLACEHOLDER = "_";
export type StrumDirection = "" | "↑" | "↓";
export enum TimeSignature {
  ONE_BAR = "1/1",
  HALF_BAR = "1/2",
  ONE_BEAT = "1/4",
  HALF_BEAT = "1/8",
  SIXTEENTH = "1/16",
  THIRTY_SECOND = "1/32",
  SIXTY_FOURTH = "1/64",
}

export const DEFAULT_TIME_SIGNATURE = TimeSignature.HALF_BEAT;

// this function gets the number of slots for the patternEditorUI
export const getDefaultSlotsForTimeSignature = (
  timeSignature: TimeSignature
): number => {
  switch (timeSignature) {
    case TimeSignature.ONE_BAR:
      return 4;
    case TimeSignature.HALF_BAR:
      return 8;
    case TimeSignature.ONE_BEAT:
      return 8;
    case TimeSignature.HALF_BEAT:
      return 8;
    case TimeSignature.SIXTEENTH:
      return 16;
    case TimeSignature.THIRTY_SECOND:
      return 32;
    case TimeSignature.SIXTY_FOURTH:
      return 64;
    // case "1/4 triplet":
    //   return 16;
    // case "1/8 triplet":
    //   return 8;
    // case "1/16 triplet":
    //   return 4;
    default:
      throw new Error("Invalid time signature: " + timeSignature);
  }
};

// This function gets the number of ticks (generated by mainClock)
export const getTicksForTimeSignature = (
  timeSignature: TimeSignature
): number => {
  switch (timeSignature) {
    case TimeSignature.ONE_BAR:
      return TICKS_IN_BAR;
    case TimeSignature.HALF_BAR:
      return TICKS_IN_HALF_BAR;
    case TimeSignature.ONE_BEAT:
      return TICKS_IN_BEAT;
    case TimeSignature.HALF_BEAT:
      return TICKS_IN_HALF_BEAT;
    case TimeSignature.SIXTEENTH:
      return TICKS_IN_SIXTEENTH;
    case TimeSignature.THIRTY_SECOND:
      return TICKS_IN_THIRTY_SECOND;
    case TimeSignature.SIXTY_FOURTH:
      return TICKS_IN_SIXTY_FOURTH;
    // case "1/4 triplet":
    //   return 16;
    // case "1/8 triplet":
    //   return 8;
    // case "1/16 triplet":
    //   return 4;
    default:
      throw new Error("Invalid time signature: " + timeSignature);
  }
};

export interface Pattern {
  id: number;
  timeSignature: TimeSignature;
  strums: StrumDirection[];
}
