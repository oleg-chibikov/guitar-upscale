export const BEATS_IN_BAR = 4;
export const TICKS_IN_HALF_BEAT = 8; // main setting affecting granularity (how many ticks in beat/bar etc) // 8 means 64 ticks in a bar
export const TICKS_IN_BEAT = TICKS_IN_HALF_BEAT * 2;
export const HALF_BEATS_IN_BAR = BEATS_IN_BAR * 2;
export const TICKS_IN_BAR = BEATS_IN_BAR * TICKS_IN_BEAT;
export const TICKS_IN_HALF_BAR = TICKS_IN_BAR / 2;
export const TICKS_IN_SIXTEENTH = TICKS_IN_BAR / 16;
export const TICKS_IN_THIRTY_SECOND = TICKS_IN_BAR / 32;
export const TICKS_IN_SIXTY_FOURTH = TICKS_IN_BAR / 64;
export enum TimeSignature {
  ONE_BAR = "1/1",
  HALF_BAR = "1/2",
  ONE_BEAT = "1/4",
  HALF_BEAT = "1/8",
  SIXTEENTH = "1/16",
  THIRTY_SECOND = "1/32",
  SIXTY_FOURTH = "1/64",
}

// This function gets the number of ticks (generated by mainClock)
export const getTicksForTimeSignature = (
  timeSignature: TimeSignature
): number => {
  switch (timeSignature) {
    case TimeSignature.ONE_BAR:
      return TICKS_IN_BAR;
    case TimeSignature.HALF_BAR:
      return TICKS_IN_HALF_BAR;
    case TimeSignature.ONE_BEAT:
      return TICKS_IN_BEAT;
    case TimeSignature.HALF_BEAT:
      return TICKS_IN_HALF_BEAT;
    case TimeSignature.SIXTEENTH:
      return TICKS_IN_SIXTEENTH;
    case TimeSignature.THIRTY_SECOND:
      return TICKS_IN_THIRTY_SECOND;
    case TimeSignature.SIXTY_FOURTH:
      return TICKS_IN_SIXTY_FOURTH;
    // case "1/4 triplet":
    //   return 16;
    // case "1/8 triplet":
    //   return 8;
    // case "1/16 triplet":
    //   return 4;
    default:
      throw new Error("Invalid time signature: " + timeSignature);
  }
};

